import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = readFileSync(new URL('../../app/javascript/controllers/reconciliation_follow_up_form_controller.js', import.meta.url), 'utf8')
  .replace('import { Controller } from "@hotwired/stimulus"', 'class Controller {}')
  .replace('export default class', 'globalThis.FormController = class');
const context = { Event: class { constructor(type, options) { this.type = type; this.bubbles = options.bubbles; } } };
vm.createContext(context);
vm.runInContext(source, context);
const form = new context.FormController();
const buttons = ['open', 'waiting', 'closed'].map(value => ({ dataset: { decision: value }, setAttribute(name, value) { this[name] = value; } }));
let focusCount = 0;
let submits = 0;
form.element = { querySelectorAll: () => buttons, submit: () => { submits++; } };
form.hasEvidenceTarget = false;
form.hasStatusTarget = form.hasDecisionTarget = true;
form.statusTarget = { value: 'open', options: buttons.map(button => ({ value: button.dataset.decision })), dispatchEvent(event) { assert.equal(event.type, 'change'); assert.equal(event.bubbles, true); form.syncDecision(); } };
form.notesTarget = { value: 'Unsubmitted reviewer text', placeholder: '', focus() { focusCount++; } };
form.decisionTarget = { textContent: '' };
form.connect();
assert.equal(form.statusTarget.value, 'open');
form.chooseDecision({ currentTarget: buttons[1] });
assert.equal(form.statusTarget.value, 'waiting');
assert.equal(buttons[1]['aria-pressed'], 'true');
assert.match(form.decisionTarget.textContent, /who owns the next step/);
form.chooseDecision({ currentTarget: buttons[2] });
assert.match(form.decisionTarget.textContent, /documented exception/);
assert.match(form.notesTarget.placeholder, /supports resolving/);
assert.equal(buttons[1]['aria-pressed'], 'false');
assert.equal(buttons[2]['aria-pressed'], 'true');
form.chooseDecision({ currentTarget: { dataset: { decision: 'invalid' } } });
assert.equal(form.statusTarget.value, 'closed');
assert.equal(focusCount, 2);
assert.equal(form.notesTarget.value, 'Unsubmitted reviewer text');
assert.equal(submits, 0);
form.statusTarget.value = 'open';
form.syncDecision();
assert.equal(buttons[0]['aria-pressed'], 'true');
assert.match(form.notesTarget.placeholder, /outstanding/);
console.log('Follow-up decisions preserve notes, validate choices, update guidance and never submit automatically.');
